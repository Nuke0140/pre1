/**
 * Builds the complete role card data with highlighted quick-scan capabilities
 * and category-grouped detailed capabilities.
 */
export function getRoleCardData(role: string): RoleCapabilityCardData {
  const normRole = (role || 'STAFF').trim().toUpperCase()
  const capabilities = getRoleCapabilities(normRole)

  const findCap = (id: string, fallbackLabel: string, fallbackCat: any): RoleCapabilityAccess => {
    const found = capabilities.find((c) => c.capabilityId === id)
    if (found) return found
    return {
      capabilityId: id,
      capabilityLabel: fallbackLabel,
      category: fallbackCat,
      description: '',
      status: 'NOT_ALLOWED',
      statusLabel: 'Not allowed',
      explanation: 'Not permitted for this role.',
      sourcePermissions: [],
    }
  }

  const highlights = {
    viewStudentFees: findCap('view_student_fees', 'View Student Fees', 'Finance'),
    messageParents: findCap('message_parents', 'Message Parents', 'Communication'),
    editAttendance: findCap('edit_attendance', 'Edit Attendance', 'Attendance'),
    viewStaffSalaries: findCap('view_staff_salaries', 'View Staff Salaries', 'Staff & HR'),
  }

  const baseConfig = ROLE_CARD_CONFIGS[normRole] || {
    title: normRole,
    badgeText: normRole,
    badgeCls: 'b-neutral',
    category: 'OPERATIONS',
    categoryLabel: 'Staff Workforce',
    tierLabel: 'Staff Role',
    tagline: 'Staff operational role in PreOne.',
    scope: 'Campus',
    boundary: 'Assigned Scope',
    accentColor: '#6B7280',
    iconBg: '#F3F4F6',
    iconColor: '#374151',
    policyTitle: 'Campus Role Scope',
    policyText: 'Operations are bounded to authorized school policies.',
    policyType: 'info',
  }

  return {
    role: normRole,
    ...baseConfig,
    highlights,
    capabilities,
  }
}

